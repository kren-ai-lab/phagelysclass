"""Shared BioSieve/MMseqs2 redundancy utilities for PhageLysClass."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import os
import random
import shutil
import subprocess
import tempfile
from pathlib import Path

import pandas as pd


DEFAULT_THRESHOLDS = [90, 70, 50, 30]
THRESHOLD_KEY_CANDIDATES = [
    "threshold",
    "min_seq_id",
    "identity",
    "min_identity",
]


def project_root_from_script(script_file: str) -> Path:
    script_dir = Path(script_file).resolve().parent
    return script_dir.parents[1]


def add_redundancy_args(
    parser: argparse.ArgumentParser,
    *,
    script_file: str,
    default_input: str | None = None,
    default_output: str | None = None,
) -> argparse.ArgumentParser:
    root = project_root_from_script(script_file)

    if default_input is not None:
        parser.add_argument(
            "--input",
            default=str(root / default_input),
            help="Task dataset.tsv.gz generated by Stage 06.",
        )

    if default_output is not None:
        parser.add_argument(
            "--output-dir",
            default=str(root / default_output),
            help="Root output directory for redundancy-reduced datasets.",
        )

    parser.add_argument(
        "--thresholds",
        nargs="+",
        type=int,
        default=DEFAULT_THRESHOLDS,
        help="MMseqs2 identity thresholds in percent (default: 90 70 50 30).",
    )
    parser.add_argument(
        "--threshold-param",
        default="auto",
        help=(
            "BioSieve mmseqs2 identity parameter name. Default 'auto' probes "
            "the installed BioSieve CLI. You can override, e.g. threshold or "
            "min_seq_id, if needed."
        ),
    )
    parser.add_argument(
        "--threads",
        type=int,
        default=max(1, (os.cpu_count() or 2) // 2),
        help=(
            "Thread hint exported through OMP_NUM_THREADS/MMSEQS_NUM_THREADS. "
            "BioSieve/MMseqs2 may additionally apply its own configured default."
        ),
    )
    parser.add_argument(
        "--reuse-existing",
        action="store_true",
        help="Reuse threshold outputs that already contain dataset.tsv.gz.",
    )
    parser.add_argument(
        "--keep-work",
        action="store_true",
        help="Keep BioSieve adapter CSVs and per-group reduced CSVs.",
    )
    return parser


def command_version(executable: str, args: list[str]) -> str:
    try:
        proc = subprocess.run(
            [executable, *args],
            capture_output=True,
            text=True,
            check=False,
        )
        text = (proc.stdout or proc.stderr or "").strip()
        return text.splitlines()[0] if text else "unknown"
    except Exception:
        return "unknown"


def package_version(name: str) -> str:
    try:
        return importlib.metadata.version(name)
    except Exception:
        return "unknown"


def preflight() -> dict[str, str]:
    biosieve = shutil.which("biosieve")
    mmseqs = shutil.which("mmseqs")

    if biosieve is None:
        raise RuntimeError(
            "BioSieve CLI not found in PATH. Install/activate BioSieve before "
            "running redundancy reduction."
        )
    if mmseqs is None:
        raise RuntimeError(
            "MMseqs2 binary ('mmseqs') not found in PATH. BioSieve's mmseqs2 "
            "reducer requires it."
        )

    return {
        "biosieve_executable": biosieve,
        "biosieve_version": package_version("biosieve"),
        "mmseqs_executable": mmseqs,
        "mmseqs_version": command_version(mmseqs, ["version"]),
    }


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(4 * 1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def load_task(path: Path) -> pd.DataFrame:
    if not path.is_file():
        raise FileNotFoundError(f"Task dataset not found: {path}")

    df = pd.read_csv(
        path,
        sep="\t",
        compression="infer",
        dtype=str,
        low_memory=False,
    ).fillna("")

    required = {"entity_id", "sequence"}
    missing = required - set(df.columns)
    if missing:
        raise KeyError(
            "Task dataset missing required columns: "
            + ", ".join(sorted(missing))
        )

    if df["entity_id"].duplicated().any():
        raise ValueError("Task contains duplicated entity_id values.")
    if df["sequence"].duplicated().any():
        raise ValueError(
            "Task contains exact sequence duplicates before redundancy stage."
        )

    return df


def _make_probe_sequences() -> tuple[str, str]:
    """Return two full-length protein sequences at ~80% identity."""
    rng = random.Random(314159)
    alphabet = "ACDEFGHIKLMNPQRSTVWY"
    seq1 = "".join(rng.choice(alphabet) for _ in range(180))
    chars = list(seq1)

    positions = rng.sample(range(len(chars)), 36)  # 80% identity
    for pos in positions:
        choices = [aa for aa in alphabet if aa != chars[pos]]
        chars[pos] = rng.choice(choices)

    return seq1, "".join(chars)


def _run_probe_once(
    *,
    biosieve_executable: str,
    key: str,
    threshold: float,
    workdir: Path,
    env: dict[str, str],
) -> int | None:
    seq1, seq2 = _make_probe_sequences()
    input_path = workdir / f"probe_{key}_{threshold}.csv"
    output_path = workdir / f"probe_{key}_{threshold}_nr.csv"
    mapping_path = workdir / f"probe_{key}_{threshold}_mapping.csv"
    report_path = workdir / f"probe_{key}_{threshold}_report.json"

    pd.DataFrame(
        {
            "id": ["probe_A", "probe_B"],
            "sequence": [seq1, seq2],
        }
    ).to_csv(input_path, index=False)

    cmd = [
        biosieve_executable,
        "reduce",
        "-i", str(input_path),
        "-o", str(output_path),
        "--strategy", "mmseqs2",
        "--mapping-output", str(mapping_path),
        "--report-output", str(report_path),
        "--set", f"mmseqs2.{key}={threshold}",
    ]

    proc = subprocess.run(
        cmd,
        cwd=workdir,
        env=env,
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0 or not output_path.is_file():
        return None

    try:
        reduced = pd.read_csv(output_path)
        return len(reduced)
    except Exception:
        return None


def detect_threshold_param(
    *,
    biosieve_executable: str,
    requested: str,
    work_root: Path,
    env: dict[str, str],
) -> str:
    if requested != "auto":
        return requested

    cache_path = work_root / ".biosieve_mmseqs2_threshold_param.json"
    if cache_path.is_file():
        try:
            payload = json.loads(cache_path.read_text(encoding="utf-8"))
            key = str(payload.get("threshold_param", "")).strip()
            if key:
                return key
        except Exception:
            pass

    probe_dir = work_root / "_biosieve_probe"
    if probe_dir.exists():
        shutil.rmtree(probe_dir)
    probe_dir.mkdir(parents=True, exist_ok=True)

    print("[PREFLIGHT] Detecting BioSieve MMseqs2 identity parameter...")

    for key in THRESHOLD_KEY_CANDIDATES:
        # An ~80%-identity pair should cluster at 70% but remain separate at 90%.
        low_n = _run_probe_once(
            biosieve_executable=biosieve_executable,
            key=key,
            threshold=0.70,
            workdir=probe_dir,
            env=env,
        )
        high_n = _run_probe_once(
            biosieve_executable=biosieve_executable,
            key=key,
            threshold=0.90,
            workdir=probe_dir,
            env=env,
        )

        if low_n == 1 and high_n == 2:
            cache_path.write_text(
                json.dumps({"threshold_param": key}, indent=2),
                encoding="utf-8",
            )
            shutil.rmtree(probe_dir, ignore_errors=True)
            print(f"            using mmseqs2.{key}")
            return key

    shutil.rmtree(probe_dir, ignore_errors=True)
    raise RuntimeError(
        "Could not automatically determine the BioSieve MMseqs2 identity "
        "parameter. Run `biosieve reduce --help` / inspect the installed "
        "BioSieve mmseqs2 strategy and rerun with "
        "`--threshold-param <parameter_name>`."
    )


def run_biosieve_group(
    *,
    group_df: pd.DataFrame,
    group_name: str,
    threshold_percent: int,
    threshold_param: str,
    work_dir: Path,
    biosieve_executable: str,
    env: dict[str, str],
) -> tuple[set[str], pd.DataFrame, dict]:
    """
    Run BioSieve MMseqs2 reduction for one biological stratum.

    Only id + sequence are passed to BioSieve. The original task metadata are
    materialized afterwards from representative IDs.
    """
    work_dir.mkdir(parents=True, exist_ok=True)

    adapter_path = work_dir / "input.csv"
    reduced_path = work_dir / "reduced.csv"
    mapping_path = work_dir / "mapping.csv"
    report_path = work_dir / "report.json"

    adapter = group_df[["entity_id", "sequence"]].rename(
        columns={"entity_id": "id"}
    )
    adapter.to_csv(adapter_path, index=False)

    threshold_fraction = threshold_percent / 100.0

    cmd = [
        biosieve_executable,
        "reduce",
        "-i", str(adapter_path),
        "-o", str(reduced_path),
        "--strategy", "mmseqs2",
        "--mapping-output", str(mapping_path),
        "--report-output", str(report_path),
        "--set", f"mmseqs2.{threshold_param}={threshold_fraction}",
    ]

    print(
        f"      [{group_name}] BioSieve MMseqs2 "
        f"identity={threshold_percent}%"
    )

    proc = subprocess.run(
        cmd,
        cwd=work_dir,
        env=env,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(
            f"BioSieve failed for group={group_name}, "
            f"threshold={threshold_percent}% (exit {proc.returncode})."
        )

    if not reduced_path.is_file():
        raise RuntimeError(f"BioSieve did not create {reduced_path}")

    reduced = pd.read_csv(reduced_path, dtype=str).fillna("")
    if "id" not in reduced.columns:
        raise KeyError(
            f"BioSieve reduced output has no 'id' column: {reduced.columns.tolist()}"
        )

    representative_ids = set(reduced["id"].astype(str))
    input_ids = set(group_df["entity_id"].astype(str))

    unknown = representative_ids - input_ids
    if unknown:
        raise RuntimeError(
            f"BioSieve returned {len(unknown):,} unknown representative IDs."
        )

    if mapping_path.is_file():
        mapping = pd.read_csv(mapping_path, dtype=str).fillna("")
    else:
        mapping = pd.DataFrame()

    report = {}
    if report_path.is_file():
        try:
            report = json.loads(report_path.read_text(encoding="utf-8"))
        except Exception:
            report = {"_warning": "Could not parse BioSieve report JSON."}

    return representative_ids, mapping, report


def reduce_task(
    *,
    task_name: str,
    input_path: Path,
    output_root: Path,
    group_col: str,
    thresholds: list[int],
    threshold_param: str,
    threads: int,
    reuse_existing: bool,
    keep_work: bool,
) -> pd.DataFrame:
    """
    Reduce one materialized task independently at each identity threshold.

    Redundancy is reduced independently inside each biological stratum defined
    by `group_col`. Threshold runs are also independent: H70 always starts from
    the original Stage-06 task, not from H90 output.
    """
    info = preflight()

    input_path = input_path.expanduser().resolve()
    output_root = output_root.expanduser().resolve()
    output_root.mkdir(parents=True, exist_ok=True)

    task = load_task(input_path)

    if group_col not in task.columns:
        raise KeyError(
            f"Requested redundancy group column '{group_col}' not present "
            f"in task. Available columns: {task.columns.tolist()}"
        )

    groups = list(task[group_col].astype(str).unique())
    if any(not x for x in groups):
        raise ValueError(
            f"Task {task_name} contains empty values in group column {group_col}."
        )

    if not thresholds:
        raise ValueError("No identity thresholds requested.")
    for threshold in thresholds:
        if threshold <= 0 or threshold > 100:
            raise ValueError(f"Invalid identity threshold: {threshold}")

    env = os.environ.copy()
    env["OMP_NUM_THREADS"] = str(threads)
    env["MMSEQS_NUM_THREADS"] = str(threads)

    resolved_param = detect_threshold_param(
        biosieve_executable=info["biosieve_executable"],
        requested=threshold_param,
        work_root=output_root,
        env=env,
    )

    print("=" * 92)
    print(f"PhageLysClass — redundancy reduction: {task_name}")
    print("=" * 92)
    print(f"Input            : {input_path}")
    print(f"Examples         : {len(task):,}")
    print(f"Grouping         : {group_col}")
    print(f"Groups           : {', '.join(groups)}")
    print(f"Thresholds       : {', '.join('H'+str(x) for x in thresholds)}")
    print(f"BioSieve         : {info['biosieve_version']}")
    print(f"MMseqs2          : {info['mmseqs_version']}")
    print(f"Identity param   : mmseqs2.{resolved_param}")
    print(f"Thread hint      : {threads}")
    print()

    overview_rows = []

    for threshold in thresholds:
        label = f"H{threshold}"
        out_dir = output_root / label
        dataset_path = out_dir / "dataset.tsv.gz"
        summary_path = out_dir / "summary.tsv"
        mapping_combined_path = out_dir / "mapping.tsv.gz"
        manifest_path = out_dir / "manifest.json"
        work_root = out_dir / "biosieve_work"

        if reuse_existing and dataset_path.is_file() and summary_path.is_file():
            print(f"[{label}] reuse existing: {dataset_path}")
            summary = pd.read_csv(summary_path, sep="\t")
            for row in summary.to_dict(orient="records"):
                if row.get("section") == "overall":
                    overview_rows.append(
                        {
                            "threshold": threshold,
                            "threshold_label": label,
                            "before": int(row["before"]),
                            "after": int(row["after"]),
                            "removed": int(row["removed"]),
                            "retained_fraction": float(row["retained_fraction"]),
                        }
                    )
            continue

        if out_dir.exists():
            # Clear only threshold-specific outputs. Other thresholds are independent.
            shutil.rmtree(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        work_root.mkdir(parents=True, exist_ok=True)

        representative_ids: set[str] = set()
        mapping_parts = []
        group_reports = {}
        summary_rows = []

        for group_name, group_df in task.groupby(group_col, sort=False):
            safe_group = "".join(
                ch if ch.isalnum() or ch in "._-" else "_"
                for ch in str(group_name)
            )
            group_work = work_root / safe_group

            reps, mapping, report = run_biosieve_group(
                group_df=group_df,
                group_name=str(group_name),
                threshold_percent=threshold,
                threshold_param=resolved_param,
                work_dir=group_work,
                biosieve_executable=info["biosieve_executable"],
                env=env,
            )

            representative_ids.update(reps)

            if not mapping.empty:
                mapping = mapping.copy()
                mapping.insert(0, "redundancy_group", str(group_name))
                mapping.insert(0, "identity_threshold", threshold)
                mapping_parts.append(mapping)

            group_reports[str(group_name)] = report

            before = len(group_df)
            after = len(reps)
            summary_rows.append(
                {
                    "section": "group",
                    "group": str(group_name),
                    "before": before,
                    "after": after,
                    "removed": before - after,
                    "retained_fraction": after / before if before else 0.0,
                }
            )

        reduced_task = task.loc[
            task["entity_id"].isin(representative_ids)
        ].copy()

        # Restore original task order deterministically.
        reduced_task["redundancy_threshold"] = threshold
        reduced_task["redundancy_threshold_label"] = label
        reduced_task["redundancy_group"] = reduced_task[group_col]

        before_total = len(task)
        after_total = len(reduced_task)

        if after_total != sum(
            row["after"] for row in summary_rows
        ):
            raise RuntimeError(
                "Combined representative count does not equal the sum of "
                "stratum-specific representative counts."
            )

        reduced_task.to_csv(
            dataset_path,
            sep="\t",
            index=False,
            compression="gzip",
        )

        overall_row = {
            "section": "overall",
            "group": "ALL",
            "before": before_total,
            "after": after_total,
            "removed": before_total - after_total,
            "retained_fraction": (
                after_total / before_total if before_total else 0.0
            ),
        }
        summary_rows.append(overall_row)
        pd.DataFrame(summary_rows).to_csv(
            summary_path,
            sep="\t",
            index=False,
        )

        if mapping_parts:
            pd.concat(
                mapping_parts,
                ignore_index=True,
                sort=False,
            ).to_csv(
                mapping_combined_path,
                sep="\t",
                index=False,
                compression="gzip",
            )
        else:
            pd.DataFrame(
                columns=[
                    "identity_threshold",
                    "redundancy_group",
                    "removed_id",
                    "representative_id",
                    "cluster_id",
                    "score",
                ]
            ).to_csv(
                mapping_combined_path,
                sep="\t",
                index=False,
                compression="gzip",
            )

        manifest = {
            "task_name": task_name,
            "input": str(input_path),
            "input_sha256": sha256_file(input_path),
            "group_column": group_col,
            "group_policy": (
                "redundancy reduced independently within biological strata"
            ),
            "threshold_percent": threshold,
            "threshold_fraction": threshold / 100.0,
            "threshold_label": label,
            "threshold_runs_are_independent": True,
            "strategy": "biosieve:mmseqs2",
            "biosieve_version": info["biosieve_version"],
            "biosieve_executable": info["biosieve_executable"],
            "mmseqs_version": info["mmseqs_version"],
            "mmseqs_executable": info["mmseqs_executable"],
            "biosieve_identity_parameter": f"mmseqs2.{resolved_param}",
            "thread_hint": threads,
            "before": before_total,
            "after": after_total,
            "removed": before_total - after_total,
            "retained_fraction": (
                after_total / before_total if before_total else 0.0
            ),
            "biosieve_reports_by_group": group_reports,
            "design_note": (
                "Stage 07 removes within-stratum sequence redundancy only. "
                "No balancing or train/validation/test split is performed. "
                "Cross-stratum homology is intentionally retained here and "
                "handled by the subsequent leakage-aware split stage."
            ),
        }
        manifest_path.write_text(
            json.dumps(manifest, indent=2),
            encoding="utf-8",
        )

        if not keep_work:
            shutil.rmtree(work_root, ignore_errors=True)

        print(
            f"[{label}] {before_total:,} -> {after_total:,} "
            f"(removed {before_total-after_total:,}; "
            f"retained {100*after_total/before_total:.2f}%)"
        )

        overview_rows.append(
            {
                "threshold": threshold,
                "threshold_label": label,
                "before": before_total,
                "after": after_total,
                "removed": before_total - after_total,
                "retained_fraction": after_total / before_total,
            }
        )

    overview = pd.DataFrame(overview_rows).sort_values(
        "threshold",
        ascending=False,
    )
    overview.to_csv(
        output_root / "redundancy_overview.tsv",
        sep="\t",
        index=False,
    )

    print()
    print(f"Overview: {output_root / 'redundancy_overview.tsv'}")
    print(
        "PASS — redundancy reduction only; no balancing or dataset splitting applied."
    )
    return overview
